package forward

import (
	"bufio"
	"io"
	"net"
	"net/http"
	"time"

	"mantou/internal/errpage"
)

// 后端连不上时，给浏览器回一页与全项目同样式的错误页。
//
// 端口转发是裸 TCP 的字节管道：它不认识管道里跑的是什么协议，可能是网页，也可能是
// 远程终端、远程桌面、数据库连接。所以"回一页错误页"这件事只在两个前提同时成立时
// 才做，缺一不可：
//
//  1. **这条连接已经注定失败。** 只在拨号后端失败之后才走到这里——此时一个字节都还没被
//     转发过，也不会再有，往连接上写什么都不可能打断一段正常会话。成功的连接完全不经过
//     这里：不多读一个字节，不多等一毫秒。
//  2. **对面确实是浏览器发来的网页请求。** 交给标准库的 http.ReadRequest 判定，不自己认
//     字节：非 HTTP 的开头（加密握手的 0x16、远程终端的 "SSH-2.0-"）在那里就会解析失败。
//     再加两道与项目其它错误页一致的闸——只认 GET/HEAD，且 Accept 里要有 text/html。
//     任何一条不满足，就按改动之前的样子直接关闭连接。
//
// 拒绝新连接的两条路径（单端口并发满、模块连接总数满）**刻意不回这一页**：那两条正是
// 过载保护，此时最不该做的就是给每条被拒的连接再加一次读、一次写和一秒等待。
//
// UDP 也没有这一页：它没有连接的概念，回过去的任何字节都会被对面的程序当成一次正常的
// 响应报文（典型如域名解析转发，客户端会把一页 HTML 当成畸形应答），那是在制造新问题。
const (
	// errPageWait 等客户端把请求发过来的时间上限。网页请求是客户端先说话的，浏览器
	// 连上之后立刻就发——请求会在我们 accept 之后约半个往返到达，即便 500 ms 的高延迟
	// 链路也只需 250 ms，1 秒留足了余量。
	//
	// 代价说清楚：对面若是"服务端先说话"的协议（远程终端、邮件、数据库这一类，客户端
	// 连上后等对方的问候语，自己一个字节都不发），它会一直等到这个期限，于是这条已经
	// 失败的连接要多留 1 秒才关闭，期间还占着一个连接名额。
	//
	// 之所以能接受：走到这里的连接都是**后端已经拨不通**的，此时既没有正常会话被耽误，
	// 也没有"本来能成功的连接"被挤掉——同一个规则下的其它连接同样连不上后端。
	// 名额被占满只会让更多注定失败的连接提前被拒，而那与它们多等一秒再失败没有分别。
	//
	// 上限也就是 1 秒：拒绝新连接的两条过载路径不经过这里（见文件头），停规则时
	// 已取消的连接会在下面第一行就被挡掉。
	errPageWait = time.Second
	// errPageMaxHeader 愿意为这次判定读进来的最大字节数。超过就当它不是我们要认的请求
	// （读到上限即结束，ReadRequest 随之报错），直接关闭。不设上限的话，一个只发头、
	// 不发结束空行的客户端能让我们一直往内存里堆。取值与错误页改写响应体的上限一致。
	errPageMaxHeader = 8 << 10
)

// replyBackendDown 在后端连不上时尽力回一页错误页，然后返回；连接由调用方关闭。
// 判定不通过、读写出错都直接返回——那正是改动之前的行为。
func (r *runner) replyBackendDown(client net.Conn) {
	// 规则正在停（或整个模块在关）就不要再等这一秒了：这一页是给人看的体面，
	// 而停规则的人正等着它停下。等待用的是连接期限而不是 ctx，所以停在等待中途
	// 的那些连接最多还会各自挂满 errPageWait——把已经取消的挡在门外能少掉大部分。
	if r.ctx.Err() != nil {
		return
	}
	// 读与写共用这一个期限：既盖住"等请求"，也盖住"写响应"，免得一个不收数据的客户端
	// 把这条协程连同它占着的连接名额一直挂住。
	if err := client.SetDeadline(time.Now().Add(errPageWait)); err != nil {
		return
	}
	req, err := http.ReadRequest(bufio.NewReader(io.LimitReader(client, errPageMaxHeader)))
	if err != nil {
		return
	}
	// 与错误页改写那一路同一套口径：POST/PUT 的失败响应多半是给程序读的，而非浏览器的
	// 客户端（命令行工具、探针、各类客户端库）要的是能解析的响应，不是一页 HTML。
	if req.Method != http.MethodGet && req.Method != http.MethodHead {
		return
	}
	if !errpage.WantsHTML(req) {
		return
	}
	// 502：本模块此刻扮演的正是网关——请求收到了，它后面的服务没能连上。
	// 页面上只回显客户端自己发来的主机名与路径，转发目标的地址一个字都不写：
	// 那是内网地址，而这一页是给任何能连上这个端口的人看的。
	_ = errpage.WriteRaw(client, req, errpage.PageFor(http.StatusBadGateway, whereOf(req)))
}

// whereOf 拼出「你访问的是」：客户端自己发来的主机名 + 路径。
// 长度由 errpage 内部截断，内容由模板转义。
func whereOf(req *http.Request) string {
	if req.URL == nil {
		return req.Host
	}
	return req.Host + req.URL.Path
}
